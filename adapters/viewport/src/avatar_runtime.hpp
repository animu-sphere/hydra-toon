// The viewport as an external host of usd-avatar-runtime's real providers
// (roadmap v0.3.0). The runtime's VRM USD bindings read the avatar beside
// Hydra, its registered owner LookAt/Expression evaluator produces every
// result, and the host matches the first result's identities to the
// delegate's resident targets and binds the fast adapter with them. Results
// are applied over the extracted scene and again at the late read, so a
// result published after extraction reaches the frame without another
// extraction, Hydra sync or static upload (design policy §34).
//
// The input is generated by this host: every expression channel and a world
// gaze point follow the host clock, stamped with the steady clock when they
// are produced. Their latencies are generated-source timings, not a capture
// device's. With a motion stage, the runtime's motion clip provider poses the
// avatar first; a clip pose has a clip time, not a production time, so pose
// latency is left unmeasured. Built only into toon-viewport-avatar; runtime
// and OpenUSD types stay in avatar_runtime.cpp.
#pragma once

#include "telemetry.hpp"

#include <toon/render_world.hpp>

#include <cstdint>
#include <memory>
#include <string>
#include <utility>
#include <vector>

namespace Toon::viewport {

class HydraScene;

struct AvatarRuntimeOptions {
  // The VRM LookAt prim; empty takes the binding's own.
  std::string look_at;
  // Producer evaluations per second on its own thread. Zero publishes one
  // result per presented frame from the frame loop, after extraction, so
  // every frame's newest result arrives late; captures are then repeatable.
  double rate = 120.0;
  // Reset the runtime instance to a new generation after this many results;
  // zero never resets.
  std::uint64_t reset_every = 0;
  // A stage holding one skeleton and its clip, which the runtime's motion
  // provider retargets onto the avatar; empty runs without one. The clip
  // plays once from the host's start and then holds its last sample.
  std::string motion;
  bool play = false;
  // Native-host regression oracle; normal hosts reuse unchanged conversions.
  bool cache = true;
  // Owner PMX bytes when the displayed stage is a composed USD/USDZ stage.
  // Empty uses the directly opened PMX root layer.
  std::string model;
  bool secondary_motion = true;
  bool loop = true;
};

// A runtime output and where it lands, with its value in the applied result.
struct AvatarRuntimeRow {
  std::string source;
  std::string target;
  std::string value;
};

struct MmdDampingNormalization {
  std::string attribute;
  float original = 0, coefficient = 0;
};

// What the overlay and the run's last lines show. The frame loop's thread
// owns it; the producer's counts are copied in when a result is taken.
struct AvatarRuntimeStatus {
  bool physics = false, playing = false, stopped = false;
  bool vrm_session = false, secondary_motion = false;
  double pending_seconds = 0;
  std::uint64_t physics_steps = 0;
  std::size_t bodies = 0, uvs = 0;
  // Owned admission records from the latest successful MMD world build.
  std::vector<MmdDampingNormalization> damping_normalizations;
  std::vector<std::string> inert_joints;
  std::string error;
  std::string avatar;
  std::string look_at;
  // The motion stage and its clip's range in seconds; empty without one.
  std::string motion;
  double clip_start = 0.0, clip_end = 0.0;
  // The applied result's retained pose sample, and how many published
  // results held the clip's boundary sample.
  std::string pose_sample;
  std::uint64_t pose_samples = 0, held_poses = 0;
  // Applied result: runtime identity and the adapter's binding.
  std::uint64_t instance = 0, frame = 0, generation = 0, input_revision = 0;
  std::string layout;
  std::uint64_t layout_version = 0, binding_epoch = 0;
  double evaluation_seconds = 0.0;
  // The first result's layout, and what of it matched resident targets.
  std::size_t joints = 0, shapes = 0, material_inputs = 0, expressions = 0;
  std::size_t skins = 0, morphs = 0, materials = 0, visibility = 0;
  std::vector<std::pair<std::string, std::string>> mismatches;
  // Owner diagnostics by origin:code, with a count.
  std::vector<std::pair<std::string, std::uint64_t>> diagnostics;
  // Results the runtime published, refused evaluations and resets.
  std::uint64_t published = 0, refused = 0, resets = 0;
  // Results applied over an extracted scene; late reads that applied a
  // result published after the frame's extraction; late reads with none
  // newer, which reapply the held result.
  std::uint64_t extracted = 0, late = 0, held = 0;
  // The applied result's selected inputs, then its bound outputs.
  std::vector<AvatarRuntimeRow> inputs, morph_rows, material_rows;
  // Milliseconds from the newest generated input sample to the runtime's
  // publication, and from publication to the late read that applied it.
  Series sample_publish{FrameTelemetry::kWindow};
  Series publish_latch{FrameTelemetry::kWindow};
};

class AvatarRuntime {
public:
  enum class Action { Play, Pause, Reset, Stop };
  // Reads the avatar at the stage's default prim with the runtime's VRM
  // bindings, registers its evaluator, publishes a first result and binds
  // what of it matches `bound`, the scene as the frame loop committed it.
  // Unmatched outputs are listed and left unbound. Throws when a provider
  // refuses the avatar, nothing matches or the adapter refuses the binding.
  static std::unique_ptr<AvatarRuntime> Start(const HydraScene& scene,
      const FrameSnapshot& bound, std::uint64_t epoch,
      const AvatarRuntimeOptions& options);
  virtual ~AvatarRuntime() = default;

  // Replaces `scene`'s bound values with the newest published result's and
  // states its input times. `late` marks the late read, after the frame's
  // extraction. On failure `scene` is unchanged.
  virtual bool Apply(FrameSnapshot& scene, bool late, std::string& error) = 0;
  // With a zero rate, evaluates and publishes the next result now; the
  // frame loop calls it after extraction. Otherwise does nothing.
  virtual void Produce() = 0;
  // Native physics hosts receive host elapsed time once before extraction.
  // Late reads only consume retained output and never request a physics tick.
  virtual void Tick(double) {}
  virtual void Control(Action) {}
  [[nodiscard]] virtual const AvatarRuntimeStatus& status() const noexcept = 0;
  // The run's last lines.
  [[nodiscard]] virtual std::string Report() const = 0;
};

} // namespace Toon::viewport
